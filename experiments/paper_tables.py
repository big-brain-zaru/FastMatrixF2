"""Emit the LaTeX tables that must not be typed by hand, from results/ and paper_data.json:
  tables_main.tex      -- the census funnel and the family invariants, input by main.tex
  tables_schemes.tex   -- the two rank-47 schemes term by term, input by supplement.tex
Usage: python paper_tables.py   (from experiments/)"""
import json, os, collections
from flip_graph import verify

R = "../results"
PD = json.load(open("../paper_data.json", encoding="utf-8"))
ON = json.load(open(os.path.join(R, "on_dissection.json"), encoding="utf-8"))


def load(p):
    return [tuple(t) for t in json.load(open(p))["scheme_bitmasks"]]


S47 = sorted(set(load(os.path.join(R, "alphatensor_444_rank47.json"))))
S47B = sorted(set(load(os.path.join(R, "records/gamma47_B_rank47.json"))))
assert verify(S47, 4, 4, 4) and verify(S47B, 4, 4, 4)

HDR = "% Generated by experiments/paper_tables.py -- do not edit by hand.\n"
out = []

# ------------------------------------------------------------------ the two rank-47 schemes
out.append(r"""\begin{table}[htbp]
\centering
\small
\caption{The two inequivalent $\mathbb{F}_2$ schemes for $\langle 4,4,4\rangle$ of rank 47, term by term.
Each factor is a $4\times4$ matrix over $\mathbb{F}_2$ written as a decimal bitmask: bit $4i+j$ is the
$(i,j)$ entry. Left: the AlphaTensor factorization as imported and re-verified. Right: the scheme found
from scratch in this work. Both satisfy all 4096 Brent equations; they share no term.}
\label{tab:schemes}
\begin{tabular}{r rrr @{\hspace{2em}} r rrr}
\toprule
\multicolumn{4}{c}{AlphaTensor, rank 47} & \multicolumn{4}{c}{This work, rank 47} \\
\cmidrule(lr){1-4}\cmidrule(lr){5-8}
$t$ & $a_t$ & $b_t$ & $c_t$ & $t$ & $a_t$ & $b_t$ & $c_t$ \\
\midrule""")
for i, (x, y) in enumerate(zip(S47, S47B), start=1):
    out.append("%d & %d & %d & %d & %d & %d & %d & %d \\\\" % (i, x[0], x[1], x[2], i, y[0], y[1], y[2]))
out.append(r"""\bottomrule
\end{tabular}
\end{table}""")

open("../tables_schemes.tex", "w").write(HDR + "\n".join(out) + "\n")
nsch = len(out)
out = []

# ------------------------------------------------------------------ Gamma rank-46 census funnel
by = PD["censuses"]["gamma46"]["by_slots"]
out.append(r"""
\begin{table}[htbp]
\centering
\caption{$\Gamma$-invariant rank-46 census, filter stage, by the number of orbits in the orbit-type
multiset. ``Count bound'' and ``projected subsystem'' are the two exact refutation tests of
Section~\ref{sec:fixedpoint}; survivors require a full from-scratch solve. Frozen state:
%s of %s multisets processed.}
\label{tab:census}
\begin{tabular}{rrrrr}
\toprule
Orbits & Multisets & Refuted, count bound & Refuted, projected subsystem & Survivors \\
\midrule""" % ("{:,}".format(PD["censuses"]["gamma46"]["processed"]).replace(",", "{,}"),
       "{:,}".format(PD["censuses"]["gamma46"]["total"]).replace(",", "{,}")))
tot = [0, 0, 0, 0]
for s in sorted(by, key=int):
    d = by[s]
    n = sum(d.values())
    row = [n, d.get("count", 0), d.get("filter", 0), d.get("pass", 0)]
    tot = [a + b for a, b in zip(tot, row)]
    out.append("%s & %s & %s & %s & %s \\\\" % tuple([s] + [("{:,}".format(v)).replace(",", "{,}") for v in row]))
out.append(r"\midrule")
out.append("total & %s & %s & %s & %s \\\\" % tuple(("{:,}".format(v)).replace(",", "{,}") for v in tot))
out.append(r"""\bottomrule
\end{tabular}
\end{table}""")

# ------------------------------------------------------------------ family invariants
f5, f6 = ON["family_5"], ON["family_6"]
out.append(r"""
\begin{table}[htbp]
\centering
\caption{The same-rank families at $5\times5$ and $6\times6$ reached by exact two-orbit rewrites under
the cyclic slot rotation $C_3$. ``Expanded'' seeds are those whose entire two-orbit neighbourhood was
enumerated to termination. Shared factors per axis measure flippability; zero would mean flip-isolated,
as both $4\times4$ rank-47 schemes are.}
\label{tab:families}
\begin{tabular}{lrr}
\toprule
 & $5\times5$, rank 93 & $6\times6$, rank 153 \\
\midrule
Distinct verified schemes & %d & %d \\
All host-verified / all $C_3$-invariant & yes / yes & yes / yes \\
Seeds fully expanded & %d & %d \\
Seeds not yet expanded & %d & %d \\
Exact instances in the expansions & %s & %s \\
Distinct factor-rank signatures & %d & %d \\
Distinct (signature, weight) classes & %d & %d \\
Shared factors per axis, range & %d--%d & %d--%d \\
Terms in common with the record, range & %s--%s & %s--%s \\
\bottomrule
\end{tabular}
\end{table}""" % (
    f5["distinct"], f6["distinct"], f5["expanded"], f6["expanded"], f5["unexpanded"], f6["unexpanded"],
    "{:,}".format(f5["expansion_instances"]), "{:,}".format(f6["expansion_instances"]),
    f5["signatures"], f6["signatures"], f5["sig_weight_classes"], f6["sig_weight_classes"],
    min(int(k.split("/")[0]) for k in f5["shared_hist"]), max(int(k.split("/")[0]) for k in f5["shared_hist"]),
    min(int(k.split("/")[0]) for k in f6["shared_hist"]), max(int(k.split("/")[0]) for k in f6["shared_hist"]),
    min(f5["common_hist"], key=int), max(f5["common_hist"], key=int),
    min(f6["common_hist"], key=int), max(f6["common_hist"], key=int)))

open("../tables_main.tex", "w").write(HDR + "\n".join(out) + "\n")
print("wrote tables_schemes.tex (%d lines) and tables_main.tex (%d lines)" % (nsch, len(out)))
