"""Geometric filter for the group census (approach B): fixed-point restriction under involutions.

Setting. G is a finite group of permutations of the L = 3n^2 bit positions (see symgroup.py) that
preserves the matmul tensor T. A census instance is (G, slots) with slots = [H_1..H_m] subgroups;
the encoding (sym_break.encode) searches a scheme  S = sum_i sum_{x in G/H_i} x.t_i  with t_i an
H_i-fixed rank-1 term, and demands S = T coordinate-wise over F2.

Lemma (even-orbit cancellation). Every g in G maps blocks to blocks, so it induces a permutation
of the tensor coordinates P = (alpha, beta, gamma) with (x.t)[P] = t[x^-1 P]. Let g be an
INVOLUTION and P a coordinate with g.P = P. Then

    S[P] = sum_i sum_{x in G/H_i : x^-1 g x in H_i} (x.t_i)[P]                        (mod 2)

because coset representatives with x^-1 g x not in H_i come in pairs {xH_i, gxH_i} and
(gx.t_i)[P] = t_i[x^-1 g^-1 P] = t_i[x^-1 P] = (x.t_i)[P]: equal values, cancelling mod 2.
Hence the Brent equations at the g-fixed coordinates involve ONLY the g-fixed terms of the
scheme, and form a small closed subsystem. If that subsystem is UNSAT for the multiset (G, slots)
then the full instance is UNSAT. Conjugate involutions give isomorphic subsystems; we take one
per G-conjugacy class and solve all of them JOINTLY on the shared representative variables.

The filter is a projection of the full encoding (same variables, same tie clauses, same
nonzero-block clauses, a subset of the Brent equations after exact cancellation), so
    filter UNSAT  =>  full instance UNSAT.
Soundness is re-checked numerically in `--selftest`: (1) the induced coordinate action preserves T
for every group element; (2) on the verified 4x4 rank-47 scheme and its order-12 group, the
cancelled sums equal T on the fixed coordinates for every involution class, term by term;
(3) at n=2 (rank 7) every census instance is solved both ways and no (filter UNSAT, full SAT)
pair may occur.

Also provided: exact enumeration of ALL subgroups of a small G (iterated joins of cyclic
subgroups) and slot enumeration over G-CONJUGACY CLASSES of stabilizers. An orbit's type depends
only on the conjugacy class of its point stabilizers (G.t contains a point with stabilizer y H y^-1
for every y), so instances differing by conjugate stabilizer choices are isomorphic and were
redundant in the previous census enumeration.
"""
import argparse, itertools, json, time
from pysat.solvers import Cadical153
import symgroup as SG
from flip_graph import verify, target_tensor


# ---------------------------------------------------------------- group utilities
def order_of(g):
    ident = tuple(range(len(g))); k = 1; h = g
    while h != ident:
        h = SG.compose(g, h); k += 1
    return k


def conj(H, y):
    yi = tuple(SG.inverse_index(y))
    return frozenset(SG.compose(SG.compose(y, h), yi) for h in H)


def conj_elem(g, y):
    yi = tuple(SG.inverse_index(y))
    return SG.compose(SG.compose(y, g), yi)


def all_subgroups(G, n):
    """Every subgroup of G: start from cyclic subgroups, join pairs until closure. Exact because
    every subgroup is generated by (a join of) its cyclic subgroups."""
    ident = tuple(range(SG.L_of(n)))
    subs = {frozenset([ident])}
    for g in G:
        subs.add(frozenset(SG.closure([g], n)))
    while True:
        new = set()
        L = list(subs)
        for i in range(len(L)):
            for j in range(i + 1, len(L)):
                if L[i] <= L[j] or L[j] <= L[i]:
                    continue
                a = next(iter(L[i] - {ident})); b = next(iter(L[j] - {ident}))
                gens = [x for x in L[i] if x != ident][:3] + [x for x in L[j] if x != ident][:3]
                K = frozenset(SG.closure(gens, n))
                if K not in subs:
                    new.add(K)
        if not new:
            break
        subs |= new
    return sorted(subs, key=len)


def subgroup_classes(G, subs):
    """G-conjugacy classes of the given subgroups; returns list of (representative, class_size)."""
    seen = set(); out = []
    for H in sorted(subs, key=lambda H: (len(H), sorted(H))):
        if H in seen:
            continue
        cls = {conj(H, y) for y in G}
        seen |= cls
        out.append((H, len(cls)))
    return out


def involution_classes(G):
    """One representative per G-conjugacy class of involutions."""
    invs = [g for g in G if order_of(g) == 2]
    seen = set(); reps = []
    for g in invs:
        if g in seen:
            continue
        cls = {conj_elem(g, y) for y in G}
        seen |= cls
        reps.append(g)
    return reps


def coset_reps(G, H):
    seen = set(); out = []
    for g in G:
        key = frozenset(SG.compose(g, h) for h in H)
        if key in seen:
            continue
        seen.add(key); out.append(g)
    return out


# ---------------------------------------------------------------- coordinate action
def coord_image(g, n, P):
    """Image of tensor coordinate P=(ia,ib,ic) under g (positions a:0..N-1, b:N.., c:2N..)."""
    N = n * n
    pos = [g[P[0]], g[N + P[1]], g[2 * N + P[2]]]
    blocks = sorted((p // N, p % N) for p in pos)
    assert [b for b, _ in blocks] == [0, 1, 2], "group element does not permute blocks"
    return (blocks[0][1], blocks[1][1], blocks[2][1])


def tensor_invariant(g, n, T):
    return {coord_image(g, n, P) for P in T} == T


def fixed_coords(g, n):
    N = n * n
    return [(ia, ib, ic) for ia in range(N) for ib in range(N) for ic in range(N)
            if coord_image(g, n, (ia, ib, ic)) == (ia, ib, ic)]


# ---------------------------------------------------------------- the filter
def build_filter(n, G, slots, T, invs=None, orbit_eqs=True):
    """Joint projected instance. Returns (clauses, nvars, stats). stats has per-involution
    fixed-coordinate count and surviving-term count."""
    N = n * n; L = 3 * N
    invs = involution_classes(G) if invs is None else invs
    st = {"nv": 0}; clauses = []

    def new():
        st["nv"] += 1
        return st["nv"]

    reps = []
    for H in slots:
        v = [new() for _ in range(L)]
        reps.append(v)
        for h in H:
            for i in range(L):
                j = h[i]
                if j != i:
                    clauses.append([-v[i], v[j]]); clauses.append([v[i], -v[j]])
        clauses.append(v[0:N]); clauses.append(v[N:2 * N]); clauses.append(v[2 * N:3 * N])

    and_cache = {}

    def AND3(x, y, z):
        key = tuple(sorted((x, y, z)))
        if key in and_cache:
            return and_cache[key]
        w = new()
        clauses.append([-w, x]); clauses.append([-w, y]); clauses.append([-w, z])
        clauses.append([w, -x, -y, -z])
        and_cache[key] = w
        return w

    stats = []; trivially_unsat = False
    for g in invs:
        F = fixed_coords(g, n)
        if orbit_eqs:
            # Fix_g is G-invariant (for y in G, yP is g-fixed iff P is y^-1 g y-fixed; conjugates of g in
            # G are involutions of the same class and the whole subsystem is G-invariant), and the scheme
            # tensor is G-invariant, so one equation per G-orbit of fixed coordinates suffices (exact).
            seen = set(); Fr = []
            for P in F:
                if P in seen: continue
                orb = {coord_image(y, n, P) for y in G}
                seen |= orb; Fr.append(P)
            F = Fr
        surv = []  # (slot index, inverse of coset rep)
        for i, H in enumerate(slots):
            for x in coset_reps(G, H):
                if conj_elem(g, tuple(SG.inverse_index(x))) in H:   # x^-1 g x in H
                    surv.append((i, SG.inverse_index(x)))
        stats.append({"fixed_coords": len(F), "surviving_terms": len(surv),
                      "target_ones_on_fixed": sum(1 for P in F if P in T)})
        for P in F:
            rhs = 1 if P in T else 0
            lits = [AND3(reps[i][inv[P[0]]], reps[i][inv[N + P[1]]], reps[i][inv[2 * N + P[2]]])
                    for i, inv in surv]
            if not lits:
                if rhs:
                    trivially_unsat = True
                    clauses.append([])   # empty clause: no fixed term can produce this 1
                continue
            cur = lits[0]
            for l in lits[1:]:
                z = new()
                clauses.append([-z, cur, l]); clauses.append([-z, -cur, -l])
                clauses.append([z, -cur, l]); clauses.append([z, cur, -l])
                cur = z
            clauses.append([cur] if rhs else [-cur])
    return clauses, st["nv"], {"involution_classes": len(invs), "per_involution": stats,
                               "trivially_unsat": trivially_unsat}


def run_filter(n, G, slots, T, conf=2000000, orbit_eqs=True):
    """Returns (verdict, seconds, stats). verdict in {'unsat','pass','budget'} -- 'pass' means the
    projected system is satisfiable (the instance survives); only 'unsat' eliminates."""
    t0 = time.time()
    cl, nv, stats = build_filter(n, G, slots, T, orbit_eqs=orbit_eqs)
    if stats["trivially_unsat"]:
        return "unsat", time.time() - t0, stats
    s = Cadical153(bootstrap_with=cl); s.conf_budget(conf)
    ok = s.solve_limited(); s.delete()
    v = "budget" if ok is None else ("pass" if ok else "unsat")
    stats["vars"] = nv; stats["clauses"] = len(cl)
    return v, time.time() - t0, stats


# ---------------------------------------------------------------- slot enumeration by class
def slots_by_class(G, n, rank, max_slots, limit, classes=None):
    """Multisets of stabilizer CLASSES with indices summing to rank, fewest slots first.
    Returns list of (slots as list of subgroup reps, class-index tuple)."""
    if classes is None:
        classes = subgroup_classes(G, all_subgroups(G, n))
    by_size = {}
    for ci, (H, _) in enumerate(classes):
        by_size.setdefault(len(G) // len(H), []).append(ci)
    sizes = sorted(by_size, reverse=True)
    out = []
    for parts in range(1, max_slots + 1):
        def rec(t, maxs, k):
            if k == 0:
                if t == 0: yield []
                return
            for s_ in sizes:
                if s_ <= maxs and s_ <= t:
                    for rest in rec(t - s_, s_, k - 1):
                        yield [s_] + rest
        for comp in rec(rank, max(sizes), parts):
            blocks = [(sz, comp.count(sz)) for sz in sorted(set(comp), reverse=True)]
            per = [list(itertools.combinations_with_replacement(by_size[sz], cnt)) for sz, cnt in blocks]
            for choice in itertools.product(*per):
                key = tuple(ci for blk in choice for ci in blk)
                out.append(([classes[ci][0] for ci in key], key))
                if len(out) >= limit:
                    return out
    return out


# ---------------------------------------------------------------- self tests
def load_gamma(n=4):
    """The 4x4 rank-47 scheme and its verified order-12 symmetry group."""
    S47 = [tuple(t) for t in json.load(open("../results/alphatensor_444_rank47.json"))["scheme_bitmasks"]]
    stab = json.load(open("../results/h1_stabilizer_alphatensor_444_rank47.json"))["elements"]
    gens = [SG.perm_sandwich(list(X), list(Y), list(Z), n) for X, Y, Z in stab] + [SG.perm_tau(n)]
    G = SG.closure(gens, n)
    return S47, G


def selftest():
    print("== selftest 1: induced coordinate action preserves T (4x4 Gamma, 2x2 Omega)")
    S47, G = load_gamma(4)
    T4 = set(target_tensor(4, 4, 4))
    assert len(G) == 12 and verify(S47, 4, 4, 4) and SG.is_invariant(S47, G, 4)
    assert all(tensor_invariant(g, 4, T4) for g in G)
    print("   Gamma: |G|=12, 47 verified, invariant, all 12 coordinate actions preserve T")

    print("== selftest 2: cancellation lemma numerically on the 47 (term level and encoding level)")
    orbs = SG.orbits(S47, G, 4)
    slots = [H for (_, _, H) in orbs]
    invs = involution_classes(G)
    print("   orbit sizes %s, involution classes %d (orders %s)" % (
        [len(o) for (_, o, _) in orbs], len(invs), [order_of(g) for g in invs]))
    for g in invs:
        F = fixed_coords(g, 4)
        # term level: sum over g-fixed terms of the actual scheme, on Fix_g, equals T|Fix_g
        fixed_terms = [t for t in S47 if SG.apply(g, t, 4) == t]
        for P in F:
            val = 0
            for (a, b, c) in fixed_terms:
                val ^= ((a >> P[0]) & 1) & ((b >> P[1]) & 1) & ((c >> P[2]) & 1)
            assert val == (1 if P in T4 else 0), "term-level cancellation lemma FAILED"
        # encoding level: surviving coset images of the orbit representatives
        val_at = {P: 0 for P in F}
        nsurv = 0
        for (t, _, H) in orbs:
            for x in coset_reps(G, H):
                if conj_elem(g, tuple(SG.inverse_index(x))) in H:
                    nsurv += 1
                    a, b, c = SG.apply(x, t, 4)
                    for P in F:
                        val_at[P] ^= ((a >> P[0]) & 1) & ((b >> P[1]) & 1) & ((c >> P[2]) & 1)
        assert all(val_at[P] == (1 if P in T4 else 0) for P in F), "encoding-level lemma FAILED"
        assert nsurv == len(fixed_terms)
        print("   involution (fixed coords %d, fixed terms %d): lemma holds at both levels" % (len(F), nsurv))
    v, dt, stats = run_filter(4, G, slots, T4)
    print("   filter on the 47's own (G, slots): %s in %.2fs, %s" % (v, dt, stats))
    assert v == "pass"

    print("== selftest 3: exhaustive cross-check at n=2, rank 7 (filter UNSAT must imply full UNSAT)")
    import sym_break as SB
    n = 2
    T2 = set(target_tensor(2, 2, 2))
    P = [[1 << p[r] for r in range(n)] for p in itertools.permutations(range(n))]
    I = [1 << r for r in range(n)]
    gens = [SG.perm_cyc(n), SG.perm_tau(n)] + [SG.perm_sandwich(M, I, I, n) for M in P[1:]] + \
           [SG.perm_sandwich(I, M, I, n) for M in P[1:]] + [SG.perm_sandwich(I, I, M, n) for M in P[1:]]
    Omega = SG.closure(gens, n)
    cyc_subs = {frozenset(SG.closure([g], n)) for g in Omega if order_of(g) > 1}
    classes = subgroup_classes(Omega, cyc_subs)
    print("   |Omega(2)| = %d, cyclic subgroup classes %d" % (len(Omega), len(classes)))
    tot = agree = 0; bad = 0; filt_unsat = full_unsat = full_sat = 0
    for (Gc, _) in classes:
        Gl = sorted(Gc)
        if not involution_classes(Gl):
            continue
        for slots, key in slots_by_class(Gl, n, 7, 7, 200):
            v, dt, _ = run_filter(n, Gl, slots, T2)
            cl, reps, terms, nv = SB.encode(n, Gl, slots, T2, False, False)
            s = Cadical153(bootstrap_with=cl); s.conf_budget(2000000); ok = s.solve_limited()
            if ok:
                sch = SB.decode(set(l for l in s.get_model() if l > 0), terms, n)
                assert verify(sch, 2, 2, 2)
            s.delete()
            tot += 1
            full = "budget" if ok is None else ("sat" if ok else "unsat")
            if v == "unsat": filt_unsat += 1
            if full == "unsat": full_unsat += 1
            if full == "sat": full_sat += 1
            if v == "unsat" and full == "sat":
                bad += 1
            if (v == "unsat") == (full == "unsat"):
                agree += 1
    print("   instances %d: filter unsat %d, full unsat %d, full sat %d, agreement %d, UNSOUND cases %d"
          % (tot, filt_unsat, full_unsat, full_sat, agree, bad))
    assert bad == 0
    print("selftest OK")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        selftest()


# ---------------------------------------------------------------- zero-cost count bound
def f2_rank(rows):
    """Rank over F2 of a list of int bitmasks."""
    r = 0; rows = [x for x in rows if x]
    while rows:
        piv = rows.pop()
        if not piv: continue
        r += 1; hb = piv.bit_length() - 1
        rows = [x ^ piv if (x >> hb) & 1 else x for x in rows]
        rows = [x for x in rows if x]
    return r


def involution_type(g, n):
    """'preserve' if g maps every block to itself, else ('swap', fixed_block)."""
    N = n * n
    blk = [g[0] // N, g[N] // N, g[2 * N] // N]
    if blk == [0, 1, 2]:
        return ("preserve", None)
    fixed = [b for b in range(3) if blk[b] == b]
    assert len(fixed) == 1
    return ("swap", fixed[0])


def count_bound(g, n, T, lb_table=None):
    """Exact lower bound on the number of g-fixed terms in any g-invariant scheme for T.

    preserve: a g-fixed term restricted to the g-fixed coordinates is a rank-1 tensor on
              FixA x FixB x FixC, so their sum T|_F needs at least max flattening rank many terms.
    swap:     g swaps two blocks and fixes one; on a fixed coordinate the two swapped factors
              coincide (v[alpha] = v[g alpha]), so the restricted term is a rank-1 MATRIX
              (unswapped-block bits) x (g-fixed bits of the fixed block); bound = rank of T|_F
              read as that matrix.
    Returns (bound, description)."""
    N = n * n
    F = fixed_coords(g, n)
    TF = [P for P in F if P in T]
    typ, fb = involution_type(g, n)
    if typ == "preserve":
        A = sorted({P[0] for P in F}); B = sorted({P[1] for P in F}); C = sorted({P[2] for P in F})
        ia = {x: i for i, x in enumerate(A)}; ib = {x: i for i, x in enumerate(B)}; ic = {x: i for i, x in enumerate(C)}
        r1 = f2_rank([sum(1 << (ib[P[1]] * len(C) + ic[P[2]]) for P in TF if P[0] == a) for a in A])
        r2 = f2_rank([sum(1 << (ia[P[0]] * len(C) + ic[P[2]]) for P in TF if P[1] == b) for b in B])
        r3 = f2_rank([sum(1 << (ia[P[0]] * len(B) + ib[P[1]]) for P in TF if P[2] == c) for c in C])
        # fixed index-set sizes (fX,fY,fZ): |A| = fX*fY, |B| = fY*fZ, |C| = fZ*fX
        import math
        prod = round(math.sqrt(len(A) * len(B) * len(C)))          # fX*fY*fZ
        fX, fY, fZ = prod // len(B), prod // len(C), prod // len(A)
        assert fX * fY == len(A) and fY * fZ == len(B) and fZ * fX == len(C)
        lb = max(r1, r2, r3)
        if lb_table:
            key = tuple(sorted((fX, fY, fZ)))
            # a sub-format obtained by deleting index values is a restriction of T|_F, so its rank
            # is also a lower bound on the number of fixed terms
            for k, v in lb_table.items():
                if all(k[i] <= key[i] for i in range(3)):
                    lb = max(lb, v)
        return lb, "preserve fixed-format <%d,%d,%d>, flattening ranks %s, bound %d" % (fX, fY, fZ, (r1, r2, r3), lb)
    # swap: rows indexed by the coordinate component of the first swapped block, cols by the fixed block
    sw = [b for b in range(3) if b != fb][0]
    rows = {}
    for P in TF:
        rows.setdefault(P[sw], 0)
        rows[P[sw]] |= 1 << P[fb]
    r = f2_rank(list(rows.values()))
    return r, "swap (fixed block %d) matrix rank %d over %d fixed coords" % (fb, r, len(F))


def fixed_count(G, slots, g):
    """Number of g-fixed terms the multiset (G, slots) produces (terms may still be zero)."""
    c = 0
    for H in slots:
        for x in coset_reps(G, H):
            if conj_elem(g, tuple(SG.inverse_index(x))) in H:
                c += 1
    return c


# ---------------------------------------------------------------- exact small-format ranks (computed, not quoted)
def small_rank_unsat(fx, fy, fz, k, conf=2000000):
    """Is 'rank(<fx,fy,fz>) <= k over F2' UNSAT? Plain (no-group) encoding; returns True/False/None."""
    la, lb, lc = fx * fy, fy * fz, fz * fx
    Tt = set(target_tensor(fx, fy, fz))
    st = {"nv": 0}; cl = []
    def new():
        st["nv"] += 1; return st["nv"]
    terms = [[new() for _ in range(la + lb + lc)] for _ in range(k)]
    def AND(x, y):
        z = new(); cl.append([-z, x]); cl.append([-z, y]); cl.append([z, -x, -y]); return z
    for ia in range(la):
        for ib in range(lb):
            ab = [AND(t[ia], t[la + ib]) for t in terms]
            for ic in range(lc):
                lits = [AND(ab[i], terms[i][la + lb + ic]) for i in range(k)]
                cur = lits[0]
                for l in lits[1:]:
                    z = new(); cl += [[-z, cur, l], [-z, -cur, -l], [z, -cur, l], [z, cur, -l]]; cur = z
                cl.append([cur] if (ia, ib, ic) in Tt else [-cur])
    s = Cadical153(bootstrap_with=cl); s.conf_budget(conf); ok = s.solve_limited(); s.delete()
    return None if ok is None else (not ok)


def small_rank_table():
    """Lower bounds on F2 ranks of small formats, COMPUTED by SAT refutation (rank <= k UNSAT
    => rank >= k+1) with a short budget, cached in ../results/small_rank_table.json. Formats that
    are not refuted within budget are absent and count_bound falls back to flattening ranks."""
    import os
    fn = "../results/small_rank_table.json"
    if os.path.exists(fn):
        return {tuple(map(int, k.split("x"))): v for k, v in json.load(open(fn)).items()}
    table = {}
    if small_rank_unsat(2, 2, 2, 6, conf=200000):
        table[(2, 2, 2)] = 7
    json.dump({"x".join(map(str, k)): v for k, v in table.items()}, open(fn, "w"))
    return table
